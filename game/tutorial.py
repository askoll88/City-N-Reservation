def get_tutorial_section(section_id: str) -> dict[str, object] | None:
    return TUTORIAL_SECTIONS.get(str(section_id or "").strip())


def format_tutorial_page(section_id: str, page: int = 0) -> tuple[str, int, int]:
    section = get_tutorial_section(section_id)
    if not section:
        return format_tutorial_home(), 0, 1

    pages = list(section.get("pages") or [])
    total_pages = max(1, len(pages))
    safe_page = max(0, min(int(page or 0), total_pages - 1))
    title = str(section.get("title") or "Обучение")
    body = str(pages[safe_page] if pages else "Раздел пуст.")
    message = (
        f"📚 ОБУЧЕНИЕ: {title.upper()}\n"
        f"Страница: {safe_page + 1}/{total_pages}\n\n"
        f"{body}"
    )
    return message, safe_page, total_pages


def format_tutorial_home() -> str:
    lines = [
        "📚 ШКОЛА ПРОВОДНИКА",
        "",
        "Старый проводник:",
        "",
        "«Я не читаю лекции. Я показываю, где обычно хоронят тех, кто не спросил вовремя.»",
        "",
        "Выбери раздел ниже или через кнопки диалога.",
    ]
    return "\n".join(lines)


def create_tutorial_home_keyboard():
    keyboard = VkKeyboard(one_time=False, inline=True)
    items = list(TUTORIAL_SECTIONS.items())
    for idx, (section_id, section) in enumerate(items):
        keyboard.add_callback_button(
            str(section["button"]),
            color=VkKeyboardColor.PRIMARY,
            payload={"command": "tutorial_page", "section": section_id, "page": 0},
        )
        if idx % 2 == 1 and idx != len(items) - 1:
            keyboard.add_line()
    return keyboard


def create_tutorial_page_keyboard(section_id: str, page: int, total_pages: int):
    keyboard = VkKeyboard(one_time=False, inline=True)
    prev_page = (page - 1) % total_pages
    next_page = (page + 1) % total_pages
    keyboard.add_callback_button(
        "Пред.",
        color=VkKeyboardColor.SECONDARY,
        payload={"command": "tutorial_page", "section": section_id, "page": prev_page},
    )
    keyboard.add_callback_button(
        f"{page + 1}/{total_pages}",
        color=VkKeyboardColor.PRIMARY,
        payload={"command": "tutorial_page", "section": section_id, "page": page},
    )
    keyboard.add_callback_button(
        "След.",
        color=VkKeyboardColor.SECONDARY,
        payload={"command": "tutorial_page", "section": section_id, "page": next_page},
    )
    keyboard.add_line()
    keyboard.add_callback_button(
        "Разделы",
        color=VkKeyboardColor.NEGATIVE,
        payload={"command": "tutorial_home"},
    )
    return keyboard


def show_tutorial_home(vk, user_id: int):
    try_edit_or_send_ui(
        vk,
        user_id,
        "tutorial",
        format_tutorial_home(),
        keyboard=create_tutorial_home_keyboard().get_keyboard(),
    )


def show_tutorial_section(vk, user_id: int, section_id: str, page: int = 0):
    message, safe_page, total_pages = format_tutorial_page(section_id, page)
    try_edit_or_send_ui(
        vk,
        user_id,
        "tutorial",
        message,
        keyboard=create_tutorial_page_keyboard(section_id, safe_page, total_pages).get_keyboard(),
    )
