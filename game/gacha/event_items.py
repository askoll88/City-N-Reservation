def get_event_outfit_passive_profile(item_name: str | None) -> dict | None:
    """Фиксированный пассивный эффект ивентового снаряжения."""
    return EVENT_OUTFIT_PASSIVES.get(str(item_name or "").strip())


def get_event_outfit_set_bonus(equipped_names: list[str] | tuple[str, ...] | set[str]) -> list[dict]:
    """Вернуть активные бонусы полных SSR-комплектов Резонанса."""
    equipped = {str(name).strip() for name in (equipped_names or []) if name}
    active = []
    for profile in EVENT_OUTFIT_SET_BONUSES.values():
        items = set(profile.get("items") or ())
        if items and items.issubset(equipped):
            active.append(profile)
    return active


def format_event_outfit_passive_stats(stats: dict | None) -> str:
    parts = []
    for key, value in (stats or {}).items():
        if not value:
            continue
        label, sign, suffix = OUTFIT_PASSIVE_LABELS.get(key, (key, "+", ""))
        parts.append(f"{label} {sign}{value}{suffix}")
    return ", ".join(parts)


