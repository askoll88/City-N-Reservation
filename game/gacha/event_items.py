EVENT_ITEM_NAMES = {row[0] for row in GACHA_EVENT_ITEMS}


def is_gacha_event_item(item_name: str | None) -> bool:
    return str(item_name or "").strip() in EVENT_ITEM_NAMES


def is_ssr_event_item(item_name: str | None) -> bool:
    return str(item_name or "").strip() in SSR_EVENT_ITEM_NAMES


def get_event_item_lore(item_name: str | None) -> str | None:
    return SSR_ITEM_LORE.get(str(item_name or "").strip())


def get_event_item_image_filename(item_name: str | None) -> str | None:
    return SSR_ITEM_IMAGES.get(str(item_name or "").strip())
